'use strict';

const protobuf = require('protobufjs');

const WIRE_TYPES = {
  double: 1,
  float: 5,
  int32: 0,
  uint32: 0,
  sint32: 0,
  fixed32: 5,
  sfixed32: 5,
  int64: 0,
  uint64: 0,
  sint64: 0,
  fixed64: 1,
  sfixed64: 1,
  bool: 0,
  string: 2,
  bytes: 2
};

const INT64_TYPES = new Set(['int64', 'uint64', 'sint64', 'fixed64', 'sfixed64']);

function isEnum(field) {
  return field.resolvedType instanceof protobuf.Enum;
}

function isMessage(field) {
  return field.resolvedType instanceof protobuf.Type;
}

function wireTypeFor(field) {
  if (isMessage(field)) return 2;
  if (isEnum(field)) return 0;
  const wt = WIRE_TYPES[field.type];
  if (wt === undefined) {
    throw new Error(`Unsupported protobuf field type: ${field.type}`);
  }
  return wt;
}

function defaultExprFor(field) {
  if (field.repeated) return '[] as unknown[]';
  if (isMessage(field)) return 'null as Record<string, unknown> | null';
  if (field.type === 'string') return "''";
  if (field.type === 'bool') return 'false';
  if (field.type === 'bytes') return 'new Uint8Array(0)';
  return '0';
}

function emitFieldEncode(field) {
  const name = field.name;
  const tag = (field.id << 3) | wireTypeFor(field);

  if (field.repeated) {
    if (isMessage(field)) {
      return [`  wRepMsg(w, ${tag}, msg.${name}, encode${field.resolvedType.name});`];
    }
    const writerMethod = isEnum(field) ? 'int32' : field.type;
    return [
      `  if (Array.isArray(msg.${name})) for (const item of msg.${name}) w.uint32(${tag}).${writerMethod}(item as never);`
    ];
  }

  if (isMessage(field)) {
    return [`  wMsg(w, ${tag}, msg.${name}, encode${field.resolvedType.name});`];
  }
  if (field.type === 'bytes') return [`  wBytes(w, ${tag}, msg.${name});`];
  if (field.type === 'string') return [`  wStr(w, ${tag}, msg.${name});`];
  if (field.type === 'bool') return [`  wBool(w, ${tag}, msg.${name});`];
  if (isEnum(field)) return [`  wEnum(w, ${tag}, msg.${name}, ${field.resolvedType.name});`];
  if (field.type === 'int64') return [`  wI64(w, ${tag}, msg.${name});`];
  if (field.type === 'double') return [`  wF64(w, ${tag}, msg.${name});`];

  return [`  if (msg.${name} != null && Number(msg.${name}) !== 0) w.uint32(${tag}).${field.type}(Number(msg.${name}));`];
}

function readScalarExpr(field) {
  if (isEnum(field)) return 'r.int32()';
  if (field.type === 'int64') return 'rI64(r)';
  if (INT64_TYPES.has(field.type)) return `toNumber(r.${field.type}())`;
  return `r.${field.type}()`;
}

function emitFieldDecode(field) {
  const name = field.name;
  const wt = wireTypeFor(field);
  const exactTag = (field.id << 3) | wt;

  if (field.repeated) {
    if (isMessage(field)) {
      return [`      case ${exactTag}: (out.${name} as unknown[]).push(decode${field.resolvedType.name}(r, r.uint32())); break;`];
    }
    if (field.type !== 'string' && field.type !== 'bytes') {
      const packedTag = (field.id << 3) | 2;
      return [
        `      case ${packedTag}: { const e = r.uint32() + r.pos; while (r.pos < e) (out.${name} as unknown[]).push(${readScalarExpr(field)}); break; }`,
        `      case ${exactTag}: (out.${name} as unknown[]).push(${readScalarExpr(field)}); break;`
      ];
    }
    return [`      case ${exactTag}: (out.${name} as unknown[]).push(${readScalarExpr(field)}); break;`];
  }

  if (isMessage(field)) {
    return [`      case ${exactTag}: out.${name} = decode${field.resolvedType.name}(r, r.uint32()); break;`];
  }

  return [`      case ${exactTag}: out.${name} = ${readScalarExpr(field)}; break;`];
}

function compactStaticModuleTarget(root, _options, callback) {
  try {
    root.resolveAll();
    const ns = root.lookup('protocol');
    if (!(ns instanceof protobuf.Namespace)) {
      throw new Error('Expected package protocol in .proto definitions');
    }

    const lines = [
      '// Code generated by pbjs (scripts/pbjs-static-target.cjs). DO NOT EDIT.',
      "import protobuf from 'protobufjs/minimal';",
      '',
      'const { Reader, Writer } = protobuf;',
      'type ProtoReader = InstanceType<typeof Reader>;',
      'type ProtoWriter = InstanceType<typeof Writer>;',
      'type MsgRecord = Record<string, unknown>;',
      'type LongLike = number | { low: number; high: number; unsigned: boolean; toNumber?: () => number };',
      '',
      'function toNumber(value: LongLike): number {',
      "  if (typeof value === 'number') return value;",
      "  if (typeof value.toNumber === 'function') return value.toNumber();",
      '  return protobuf.util.LongBits.from(value).toNumber(Boolean(value.unsigned));',
      '}',
      '',
      'const rI64 = (r: ProtoReader): number => toNumber(r.int64());',
      'const toReader = (input: ProtoReader | Uint8Array): ProtoReader => (input instanceof Reader ? input : new Reader(input));',
      "const wStr = (w: ProtoWriter, tag: number, v: unknown): void => { if (v != null && v !== '') w.uint32(tag).string(String(v)); };",
      'const wBool = (w: ProtoWriter, tag: number, v: unknown): void => { if (v) w.uint32(tag).bool(true); };',
      'const wI64 = (w: ProtoWriter, tag: number, v: unknown): void => { const n = Number(v); if (n) w.uint32(tag).int64(n); };',
      'const wF64 = (w: ProtoWriter, tag: number, v: unknown): void => { const n = Number(v); if (n) w.uint32(tag).double(n); };',
      'const wBytes = (w: ProtoWriter, tag: number, v: unknown): void => { if (v != null && (v as { length?: number }).length) w.uint32(tag).bytes(v as Uint8Array); };',
      "const wEnum = (w: ProtoWriter, tag: number, v: unknown, map: Record<string, number>): void => { if (v == null) return; const n = typeof v === 'string' ? map[v] ?? 0 : Number(v); if (n) w.uint32(tag).int32(n); };",
      'const wMsg = (w: ProtoWriter, tag: number, v: unknown, enc: (m: MsgRecord, w: ProtoWriter) => ProtoWriter): void => { if (v != null) enc(v as MsgRecord, w.uint32(tag).fork()).ldelim(); };',
      'const wRepMsg = (w: ProtoWriter, tag: number, v: unknown, enc: (m: MsgRecord, w: ProtoWriter) => ProtoWriter): void => { if (Array.isArray(v)) for (const item of v) if (item != null) enc(item as MsgRecord, w.uint32(tag).fork()).ldelim(); };',
      '',
      'export interface StaticPayloadCodec {',
      '  encode(msg: MsgRecord): Uint8Array<ArrayBufferLike>;',
      '  decode(bytes: Uint8Array): MsgRecord;',
      '}',
      ''
    ];

    const messageNames = [];

    for (const nested of ns.nestedArray) {
      if (nested instanceof protobuf.Enum) {
        lines.push(`export const ${nested.name} = {`);
        for (const [key, val] of Object.entries(nested.values)) {
          lines.push(`  ${key}: ${val},`);
        }
        lines.push('} as const;', '');
      }
    }

    for (const nested of ns.nestedArray) {
      if (!(nested instanceof protobuf.Type)) continue;
      messageNames.push(nested.name);
      const fields = nested.fieldsArray.map((f) => f.resolve());

      const msgParam = fields.length > 0 ? 'msg' : '_msg';
      lines.push(`export function encode${nested.name}(${msgParam}: MsgRecord, w: ProtoWriter = Writer.create()): ProtoWriter {`);
      for (const field of fields) {
        lines.push(...emitFieldEncode(field));
      }
      lines.push('  return w;', '}', '');

      lines.push(`export function decode${nested.name}(input: ProtoReader | Uint8Array, length?: number): MsgRecord {`);
      lines.push('  const r = toReader(input);');
      lines.push('  const end = length === undefined ? r.len : r.pos + length;');
      lines.push('  const out: MsgRecord = {');
      for (const field of fields) {
        lines.push(`    ${field.name}: ${defaultExprFor(field)},`);
      }
      lines.push('  };');
      lines.push('  while (r.pos < end) {');
      lines.push('    const tag = r.uint32();');
      if (fields.length > 0) {
        lines.push('    switch (tag) {');
        for (const field of fields) {
          lines.push(...emitFieldDecode(field));
        }
        lines.push('      default: r.skipType(tag & 7); break;', '    }');
      } else {
        lines.push('    r.skipType(tag & 7);');
      }
      lines.push('  }', '  return out;', '}', '');
    }

    lines.push('export const staticMessageCodecs: Record<string, StaticPayloadCodec> = {');
    for (const name of messageNames) {
      lines.push(
        `  ${name}: { encode: (m) => encode${name}(m).finish(), decode: (b) => decode${name}(b) },`
      );
    }
    lines.push('};', '');

    callback(null, lines.join('\n'));
  } catch (err) {
    callback(err);
  }
}

compactStaticModuleTarget.description = 'Compact CSP-safe TypeScript static module target for protobufjs/minimal';
module.exports = compactStaticModuleTarget;
